// Writes dist/draco.js: three.js's Draco decoder as one classic script, so
// the viewer can open Draco-compressed .glb files straight from disk. The
// viewer loads it only when a model needs it. Run by `npm run bundle`.
import fs from "node:fs";

const dir = "node_modules/three/examples/jsm/libs/draco/gltf";
const wrapper = fs.readFileSync(`${dir}/draco_wasm_wrapper.js`, "utf8");
const wasm = fs.readFileSync(`${dir}/draco_decoder.wasm`).toString("base64");
fs.mkdirSync("dist", { recursive: true });
fs.writeFileSync(
  "dist/draco.js",
  `/* Draco decoder from three@${JSON.parse(fs.readFileSync("node_modules/three/package.json", "utf8")).version} (Apache-2.0, Google). Generated by make-draco.mjs. */\n` +
    `window.__dracoLibrary = { wrapper: ${JSON.stringify(wrapper)}, wasm: ${JSON.stringify(wasm)} };\n`,
);
console.log("dist/draco.js", fs.statSync("dist/draco.js").size, "bytes");
