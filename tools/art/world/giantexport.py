"""Writes games/hatchery-heist/src/shared/GiantEggArt.luau from giantegg.py:
the Giant Golden Egg as a prop in WorldArt's format, so shared/VoxelProp
builds it (kind "event" props only; WorldArt.luau is never touched).

    python3 tools/art/world/giantexport.py

Needs numpy.
"""
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.dirname(HERE))

import importlib.util  # noqa: E402

from vkit import PAL, VOX  # noqa: E402

_spec = importlib.util.spec_from_file_location('world_export', os.path.join(HERE, 'export.py'))
export = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(export)
import props  # noqa: E402
import giantegg  # noqa: E402,F401  (registers the props)

ROOT = export.ROOT
OUT = os.path.join(ROOT, 'games', 'hatchery-heist', 'src', 'shared', 'GiantEggArt.luau')
num = export.num


def event_ids():
    return sorted(pid for pid, (_fn, kind, *_rest) in props.REGISTRY.items() if kind == 'event')


def export_all():
    lines = [
        '--!strict',
        '-- GENERATED by tools/art/world/giantexport.py from tools/art/world/giantegg.py.',
        '-- Do not edit: change the art there and run',
        '-- `python3 tools/art/world/giantexport.py` (needs numpy).',
        '--',
        '-- The Giant Golden Egg (timed events, config/events.luau) in WorldArt\'s',
        '-- format: voxel boxes, seven numbers a box, Y up, front -Z, base at Y = 0.',
        '-- Register it with shared/VoxelProp to build it.',
        '',
        'local WorldArt = require("./WorldArt")',
        '',
        'local GiantEggArt: { [string]: WorldArt.Prop } = {',
    ]
    report = []
    dump = {}
    for pid in event_ids():
        p = props.make(pid)
        f, parts = export.fit(p)
        allv = [k for *_, v in parts for k in v]
        lo = [min(q[i] for q in allv) for i in range(3)]
        hi = [max(q[i] for q in allv) + 1 for i in range(3)]
        ox, oy, oz = -(lo[0] + hi[0]) / 2, -(lo[1] + hi[1]) / 2, -lo[2]
        vs = VOX * f
        palette, index, part_lines, total = [], {}, [], 0
        dump[pid] = dict(voxel=round(vs, 3), palette=palette, parts=[])
        present = {x[0] for x in parts if x[4]}
        for name, anim, parent, pivot, v in parts:
            if not v:
                continue
            if parent not in present:
                parent = None
            bx = export.boxes_of({k: (PAL[c][0], PAL[c][1] > 0) for k, c in v.items()})
            total += len(bx)
            flat = []
            for (x, y, z, sx, sy, sz, key) in bx:
                if key not in index:
                    rgb, glow = key
                    palette.append('%02X%02X%02X%s' % (rgb[0], rgb[1], rgb[2], '*' if glow else ''))
                    index[key] = len(palette)
                flat += [num(x + ox), num(z + oz), num(y + oy), str(sx), str(sz), str(sy), str(index[key])]
            dump[pid]['parts'].append(dict(name=name, boxes=[float(x) for x in flat]))
            px, py, pz = (c / vs for c in pivot)
            part_lines += ['\t\t\t{', f'\t\t\tname = "{name}",', f'\t\t\tanim = "{anim}",']
            if parent:
                part_lines.append(f'\t\t\tparent = "{parent}",')
            part_lines.append(f'\t\t\tpivot = {{ {num(px + ox)}, {num(pz + oz)}, {num(py + oy)} }},')
            part_lines.append('\t\t\tboxes = {')
            for i in range(0, len(flat), 28):
                part_lines.append('\t\t\t\t' + ', '.join(flat[i:i + 28]) + ',')
            part_lines += ['\t\t\t},', '\t\t\t},']
        size = [hi[0] - lo[0], hi[2] - lo[2], hi[1] - lo[1]]
        ax, ay, az = (c / vs for c in (p.anchor or (0, 0, 0)))
        anchor = [num(ax + ox), num(az + oz), num(ay + oy)]
        lines += [
            f'\t{pid} = {{',
            f'\t\tkind = "{p.kind}",',
            f'\t\tvoxel = {round(vs, 3)},',
            f'\t\tsize = {{ {size[0]}, {size[1]}, {size[2]} }},',
            f'\t\tanchor = {{ {", ".join(anchor)} }},',
            f'\t\tnote = {export.lua_str(p.note)},',
            '\t\tpalette = { ' + ', '.join(f'"{s}"' for s in palette) + ' },',
            '\t\tparts = {',
        ] + part_lines + ['\t},', '\t},']
        report.append((pid, round(vs, 2), total, p.budget, [round(s * vs, 1) for s in size]))
    lines += ['}', '', 'return GiantEggArt', '']
    with open(OUT, 'w') as fh:
        fh.write('\n'.join(lines))
    # the Parts version for build.py's review render (build/, never committed)
    os.makedirs(os.path.join(ROOT, 'build', 'world'), exist_ok=True)
    import json
    with open(os.path.join(ROOT, 'build', 'world', 'giantart.json'), 'w') as fh:
        json.dump(dump, fh)
    for tool in ('stylua', os.path.expanduser('~/bin/stylua'), '/opt/tools/stylua'):
        try:
            subprocess.run([tool, OUT], check=True, capture_output=True)
            break
        except (FileNotFoundError, subprocess.CalledProcessError):
            continue
    return report


if __name__ == '__main__':
    rep = export_all()
    for pid, vs, n, budget, size in rep:
        flag = '' if n <= budget else '  OVER BUDGET'
        print(f'{pid:20s} voxel {vs:<4} {n:4d}/{budget:<4d} boxes  size {size}{flag}')
    print(f'wrote {os.path.relpath(OUT, ROOT)}: {len(rep)} props, {sum(r[2] for r in rep)} boxes')
