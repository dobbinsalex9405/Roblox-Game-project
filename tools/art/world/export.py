"""Writes games/hatchery-heist/src/shared/WorldArt.luau from props.py (and
decor.py): every world prop as voxel boxes the game builds from Parts.

    python3 tools/art/world/export.py [--only OakTree,Bush]

Props are modelled at 0.1-stud voxels. For Parts that is far too many boxes,
so each prop is resampled to the finest voxel size (0.2, 0.3, ... studs) at
which its boxes fit its budget (80 by default), and same-coloured voxels are
merged into boxes. Thin glowing bits (lamps, gems) are kept when they cover
a fair share of a coarse voxel.
"""
import argparse
import os
import subprocess
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.dirname(HERE))

import vkit  # noqa: E402
from vkit import PAL, VOX  # noqa: E402
from voxkit import greedy_boxes, merged_boxes  # noqa: E402
import props  # noqa: E402
import decor  # noqa: E402,F401  (registers more props)
import apartment  # noqa: E402,F401
import tower  # noqa: E402,F401

ROOT = os.path.normpath(os.path.join(HERE, '..', '..', '..'))
OUT = os.path.join(ROOT, 'games', 'hatchery-heist', 'src', 'shared', 'WorldArt.luau')
FACTORS = (2, 3, 4, 5, 6, 8, 10, 12)


def coarse(grid, f, thr=0.4, glow_frac=0.12):
    """grid resampled to f x f x f blocks -> {(i, j, k): palette index},
    block coordinates in units of f voxels, aligned to the world grid."""
    C, o = grid.c, grid.o
    if vkit.FAMILY:
        lut = np.arange(len(PAL), dtype=C.dtype)
        for a, b in vkit.FAMILY.items():
            seen = {a}
            while b in vkit.FAMILY and b not in seen:  # follow chains: a speckle of a speckle
                seen.add(b)
                b = vkit.FAMILY[b]
            lut[a] = b
        C = lut[C]
    pad0 = [int(o[i] % f) for i in range(3)]
    shape = [C.shape[i] + pad0[i] for i in range(3)]
    pad1 = [(-shape[i]) % f for i in range(3)]
    Cp = np.pad(C, [(pad0[i], pad1[i]) for i in range(3)])
    n = [Cp.shape[i] // f for i in range(3)]
    B = Cp.reshape(n[0], f, n[1], f, n[2], f).transpose(0, 2, 4, 1, 3, 5).reshape(n[0], n[1], n[2], f ** 3)
    filled = (B > 0).sum(-1)
    ids = [int(i) for i in np.unique(C) if i]
    if not ids:
        return {}
    counts = np.stack([(B == i).sum(-1) for i in ids], -1)
    best = np.array(ids)[counts.argmax(-1)]
    glow_ids = [k for k, i in enumerate(ids) if PAL[i][1] > 0]
    if glow_ids:
        gc = counts[..., glow_ids]
        gbest = np.array(ids)[np.array(glow_ids)][gc.argmax(-1)]
        use_glow = gc.max(-1) >= glow_frac * f ** 3
        best = np.where(use_glow, gbest, best)
        keep = (filled >= thr * f ** 3) | use_glow
    else:
        keep = filled >= thr * f ** 3
    base = [(o[i] - pad0[i]) // f for i in range(3)]
    out = {}
    for i, j, k in np.argwhere(keep):
        out[(int(i + base[0]), int(j + base[1]), int(k + base[2]))] = int(best[i, j, k])
    return out


def boxes_of(vox):
    a, b = greedy_boxes(vox), merged_boxes(vox)
    return b if len(b) <= len(a) else a


def resample(p, f):
    parts = []
    for name, anim, parent, pivot, g in p.parts:
        v = {}
        for thr in (0.35, 0.2, 0.05):
            v = coarse(g, f, thr)
            if v:
                break
        parts.append((name, anim, parent, pivot, v))
    return parts


def fit(p):
    for f in (p.factors or FACTORS):
        parts = resample(p, f)
        n = sum(len(boxes_of(v)) for *_, v in parts if v)
        if n <= p.budget:
            return f, parts
    return f, parts


def num(v):
    v = round(v * 2) / 2
    return str(int(v)) if v == int(v) else repr(v)


def lua_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def export(only=None):
    ids = [i for i in props.REGISTRY if not only or i in only]
    lines = [
        '--!strict',
        '-- GENERATED by tools/art/world/export.py from tools/art/world/props.py and',
        '-- decor.py. Do not edit: change the art there and run',
        '-- `python3 tools/art/world/export.py` (needs numpy).',
        '--',
        '-- Every world prop (trees, pedestals, belt, elevator, ladder, floor decor)',
        '-- as voxel boxes, in voxels of the prop\'s own `voxel` size (studs).',
        '-- Y is up, the front is -Z, the base is at Y = 0 and X, Z are centred.',
        '-- Each part lists its boxes as a flat array, seven numbers a box:',
        '-- min x, min y, min z, size x, size y, size z, palette index. A palette',
        '-- entry ending in "*" glows (Neon). `anchor`, when set, is the point the',
        '-- game places (for example the belt centreline of a rail section).',
        '',
        'export type Part = {',
        '\tname: string,',
        '\tanim: string,',
        '\tparent: string?,',
        '\tpivot: { number },',
        '\tboxes: { number },',
        '}',
        'export type Prop = {',
        '\tkind: string,',
        '\tvoxel: number,',
        '\tsize: { number },',
        '\tpalette: { string },',
        '\tparts: { Part },',
        '\tanchor: { number }?,',
        '\tfloor: number?,',
        '\tzone: string?,',
        '\tnote: string,',
        '}',
        '',
        'local WorldArt: { props: { [string]: Prop } } = {',
        '\tprops = {',
    ]
    report = []
    dump = {}
    for pid in sorted(ids):
        p = props.make(pid)
        f, parts = fit(p)
        allv = [k for *_, v in parts for k in v]
        lo = [min(q[i] for q in allv) for i in range(3)]
        hi = [max(q[i] for q in allv) + 1 for i in range(3)]
        ox, oy, oz = -(lo[0] + hi[0]) / 2, -(lo[1] + hi[1]) / 2, -lo[2]
        vs = VOX * f
        palette, index = [], {}
        part_lines = []
        total = 0
        dump[pid] = dict(voxel=round(VOX * f, 3), palette=palette, parts=[])
        present = {x[0] for x in parts if x[4]}
        for name, anim, parent, pivot, v in parts:
            if not v:
                continue
            if parent not in present:
                parent = None
            bx = boxes_of({k: (PAL[c][0], PAL[c][1] > 0) for k, c in v.items()})
            total += len(bx)
            flat = []
            for (x, y, z, sx, sy, sz, key) in bx:
                if key not in index:
                    rgb, glow = key
                    palette.append('%02X%02X%02X%s' % (rgb[0], rgb[1], rgb[2], '*' if glow else ''))
                    index[key] = len(palette)
                flat += [num(x + ox), num(z + oz), num(y + oy), str(sx), str(sz), str(sy), str(index[key])]
            dump[pid]['parts'].append(dict(name=name, boxes=[float(v) for v in flat]))
            px, py, pz = (c / vs for c in pivot)
            part_lines.append('\t\t\t\t{')
            part_lines.append(f'\t\t\t\t\tname = "{name}",')
            part_lines.append(f'\t\t\t\t\tanim = "{anim}",')
            if parent:
                part_lines.append(f'\t\t\t\t\tparent = "{parent}",')
            part_lines.append(f'\t\t\t\t\tpivot = {{ {num(px + ox)}, {num(pz + oz)}, {num(py + oy)} }},')
            part_lines.append('\t\t\t\t\tboxes = {')
            for i in range(0, len(flat), 7 * 4):
                part_lines.append('\t\t\t\t\t\t' + ', '.join(flat[i:i + 7 * 4]) + ',')
            part_lines.append('\t\t\t\t\t},')
            part_lines.append('\t\t\t\t},')
        size = [hi[0] - lo[0], hi[2] - lo[2], hi[1] - lo[1]]
        lines.append(f'\t\t{pid} = {{')
        lines.append(f'\t\t\tkind = "{p.kind}",')
        lines.append(f'\t\t\tvoxel = {round(vs, 3)},')
        lines.append(f'\t\t\tsize = {{ {size[0]}, {size[1]}, {size[2]} }},')
        if p.anchor is not None:
            ax, ay, az = (c / vs for c in p.anchor)
            dump[pid]['anchor'] = [float(num(ax + ox)), float(num(az + oz)), float(num(ay + oy))]
            lines.append(f'\t\t\tanchor = {{ {num(ax + ox)}, {num(az + oz)}, {num(ay + oy)} }},')
        if p.floor is not None:
            lines.append(f'\t\t\tfloor = {p.floor},')
        if p.zone is not None:
            lines.append(f'\t\t\tzone = "{p.zone}",')
        lines.append(f'\t\t\tnote = {lua_str(p.note)},')
        lines.append('\t\t\tpalette = { ' + ', '.join(f'"{s}"' for s in palette) + ' },')
        lines.append('\t\t\tparts = {')
        lines += part_lines
        lines.append('\t\t\t},')
        lines.append('\t\t},')
        report.append((pid, round(vs, 2), total, [round(s * vs, 1) for s in size]))
    lines += ['\t},', '}', '', 'return WorldArt', '']
    with open(OUT, 'w') as fh:
        fh.write('\n'.join(lines))
    os.makedirs(os.path.join(ROOT, 'build', 'world'), exist_ok=True)
    import json
    with open(os.path.join(ROOT, 'build', 'world', 'worldart.json'), 'w') as fh:
        json.dump(dump, fh)
    for tool in ('stylua', '/opt/tools/stylua'):
        try:
            subprocess.run([tool, OUT], check=True, capture_output=True)
            break
        except (FileNotFoundError, subprocess.CalledProcessError):
            continue
    return report


if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('--only')
    a = ap.parse_args()
    rep = export(set(a.only.split(',')) if a.only else None)
    for pid, vs, n, size in rep:
        print(f'{pid:24s} voxel {vs:<4} {n:4d} boxes  size {size}')
    print(f'wrote {os.path.relpath(OUT, ROOT)}: {len(rep)} props, {sum(r[2] for r in rep)} boxes')
