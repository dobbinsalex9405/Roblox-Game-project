"""Writes games/hatchery-heist/src/shared/ShopArt.luau from shop.py: the Golden
Egg Shop's props (the same format as WorldArt.luau, so shared/VoxelProp
builds them) and its layout, in Roblox's frame.

    python3 tools/art/world/shopexport.py

Needs numpy. Also writes build/world/shopart.json for shopbuild.py.
"""
import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.dirname(HERE))

import importlib.util  # noqa: E402

from vkit import PAL, VOX  # noqa: E402

# world/export.py (fit, boxes_of, num); tools/art/export.py shares its name
_spec = importlib.util.spec_from_file_location('world_export', os.path.join(HERE, 'export.py'))
export = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(export)
import props  # noqa: E402
import shop  # noqa: E402

ROOT = export.ROOT
OUT = os.path.join(ROOT, 'games', 'hatchery-heist', 'src', 'shared', 'ShopArt.luau')
num = export.num


def shop_ids():
    return sorted(pid for pid, (_fn, kind, *_rest) in props.REGISTRY.items() if kind in ('shop', 'shopdisplay'))


def rb(v):
    """art frame (x right, y back, z up) -> Roblox (X, Y up, Z back)"""
    x, y, z = v
    return (x, z, y)


def vec(v):
    return '{ ' + ', '.join(num(c) if abs(c * 2 - round(c * 2)) < 1e-9 else repr(round(c, 3)) for c in v) + ' }'


def board(b):
    # a text area on a face that looks toward -Z: centre (x, y, z) and size, Roblox frame
    return f'{{ at = {vec(rb((b["x"], b["face_y"], b["z"])))}, size = {{ {num(b["w"])}, {num(b["h"])} }} }}'


def export_all():
    ids = shop_ids()
    lines = [
        '--!strict',
        '-- GENERATED by tools/art/world/shopexport.py from tools/art/world/shop.py.',
        '-- Do not edit: change the art there and run',
        '-- `python3 tools/art/world/shopexport.py` (needs numpy).',
        '--',
        '-- The Golden Egg Shop, Hatchery Heist\'s walk-in Robux shop: its props in',
        '-- WorldArt\'s format (voxel boxes, seven numbers a box; a palette entry',
        '-- ending in "*" glows; BEE6FF is window glass) and its layout. Layout',
        '-- positions are studs in the building\'s own frame: origin at the middle',
        '-- of the floor at ground level, the door at -Z, Y up. `turn` is degrees',
        '-- about Y. Boards are text areas on a face that looks toward -Z.',
        '',
        'local WorldArt = require("./WorldArt")',
        '',
        'export type Entry = {',
        '\ttype: string,',
        '\tprop: string?,',
        '\tat: { number },',
        '\tturn: number,',
        '\tcollide: boolean?,',
        '\tkey: string?,',
        '\tkind: string?,',
        '\tplinth: string?,',
        '\titem: string?,',
        '\trange: number?,',
        '\tbrightness: number?,',
        '\tslot: string?,',
        '\tboard: { at: { number }, size: { number } }?,',
        '\tspecies: string?,',
        '\tsize: number?,',
        '}',
        '',
        'local ShopArt: {',
        '\tsize: { number },',
        '\tcard: { at: { number }, size: { number } },',
        '\tplinthTop: { [string]: number },',
        '\tlayout: { Entry },',
        '\tprops: { [string]: WorldArt.Prop },',
        '} = {',
        f'\tsize = {vec(rb((shop.W, shop.D, shop.RIDGE)))},',
        f'\tcard = {board(shop.PLINTH_CARD)},',
        '\tplinthTop = { ' + ', '.join(f'{k} = {num(v)}' for k, v in sorted(shop.PLINTH_TOP.items())) + ' },',
        '\tlayout = {',
    ]
    for e in shop.LAYOUT:
        fields = [f'type = "{e["type"]}"']
        if 'prop' in e:
            fields.append(f'prop = "{e["prop"]}"')
        fields.append(f'at = {vec(rb(e["at"]))}')
        fields.append(f'turn = {num(e.get("turn", 0))}')
        if 'collide' in e:
            fields.append(f'collide = {"true" if e["collide"] else "false"}')
        for k in ('key', 'kind', 'plinth', 'item', 'slot', 'species'):
            if k in e:
                fields.append(f'{k} = "{e[k]}"')
        for k in ('range', 'brightness', 'size'):
            if k in e:
                fields.append(f'{k} = {num(e[k])}')
        if 'board' in e:
            fields.append(f'board = {board(e["board"])}')
        lines.append('\t\t{ ' + ', '.join(fields) + ' },')
    lines += ['\t},', '\tprops = {']
    report, dump = [], {}
    for pid in ids:
        p = props.make(pid)
        f, parts = export.fit(p)
        allv = [k for *_, v in parts for k in v]
        lo = [min(q[i] for q in allv) for i in range(3)]
        hi = [max(q[i] for q in allv) + 1 for i in range(3)]
        ox, oy, oz = -(lo[0] + hi[0]) / 2, -(lo[1] + hi[1]) / 2, -lo[2]
        vs = VOX * f
        palette, index, part_lines, total = [], {}, [], 0
        dump[pid] = dict(voxel=round(vs, 3), palette=palette, parts=[])
        present = {x[0] for x in parts if x[4]}
        for name, anim, parent, pivot, v in parts:
            if not v:
                continue
            if parent not in present:
                parent = None
            bx = export.boxes_of({k: (PAL[c][0], PAL[c][1] > 0) for k, c in v.items()})
            total += len(bx)
            flat = []
            for (x, y, z, sx, sy, sz, key) in bx:
                if key not in index:
                    rgb, glow = key
                    palette.append('%02X%02X%02X%s' % (rgb[0], rgb[1], rgb[2], '*' if glow else ''))
                    index[key] = len(palette)
                flat += [num(x + ox), num(z + oz), num(y + oy), str(sx), str(sz), str(sy), str(index[key])]
            dump[pid]['parts'].append(dict(name=name, boxes=[float(t) for t in flat]))
            px, py, pz = (c / vs for c in pivot)
            part_lines += ['\t\t\t\t{', f'\t\t\t\t\tname = "{name}",', f'\t\t\t\t\tanim = "{anim}",']
            if parent:
                part_lines.append(f'\t\t\t\t\tparent = "{parent}",')
            part_lines.append(f'\t\t\t\t\tpivot = {{ {num(px + ox)}, {num(pz + oz)}, {num(py + oy)} }},')
            part_lines.append('\t\t\t\t\tboxes = {')
            for i in range(0, len(flat), 28):
                part_lines.append('\t\t\t\t\t\t' + ', '.join(flat[i:i + 28]) + ',')
            part_lines += ['\t\t\t\t\t},', '\t\t\t\t},']
        size = [hi[0] - lo[0], hi[2] - lo[2], hi[1] - lo[1]]
        ax, ay, az = (c / vs for c in (p.anchor or (0, 0, 0)))
        anchor = [num(ax + ox), num(az + oz), num(ay + oy)]
        dump[pid]['anchor'] = [float(a) for a in anchor]
        lines += [
            f'\t\t{pid} = {{',
            f'\t\t\tkind = "{p.kind}",',
            f'\t\t\tvoxel = {round(vs, 3)},',
            f'\t\t\tsize = {{ {size[0]}, {size[1]}, {size[2]} }},',
            f'\t\t\tanchor = {{ {", ".join(anchor)} }},',
            f'\t\t\tnote = {export.lua_str(p.note)},',
            '\t\t\tpalette = { ' + ', '.join(f'"{s}"' for s in palette) + ' },',
            '\t\t\tparts = {',
        ] + part_lines + ['\t\t\t},', '\t\t},']
        report.append((pid, round(vs, 2), total, p.budget, [round(s * vs, 1) for s in size]))
    lines += ['\t},', '}', '', 'return ShopArt', '']
    with open(OUT, 'w') as fh:
        fh.write('\n'.join(lines))
    os.makedirs(os.path.join(ROOT, 'build', 'world'), exist_ok=True)
    with open(os.path.join(ROOT, 'build', 'world', 'shopart.json'), 'w') as fh:
        json.dump(dump, fh)
    for tool in ('stylua', '/opt/tools/stylua'):
        try:
            subprocess.run([tool, OUT], check=True, capture_output=True)
            break
        except (FileNotFoundError, subprocess.CalledProcessError):
            continue
    return report


if __name__ == '__main__':
    rep = export_all()
    for pid, vs, n, budget, size in rep:
        flag = '' if n <= budget else '  OVER BUDGET'
        print(f'{pid:20s} voxel {vs:<4} {n:4d}/{budget:<4d} boxes  size {size}{flag}')
    print(f'wrote {os.path.relpath(OUT, ROOT)}: {len(rep)} props, {sum(r[2] for r in rep)} boxes')
