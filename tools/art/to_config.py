"""Roster to game: writes the generated part of Hatchery Heist's
config/creatures.luau, so every creature that is built and uploaded can hatch.

    python3 tools/art/to_config.py           rewrite the generated block
    python3 tools/art/to_config.py --check   exit 1 if the block is out of date
    python3 tools/art/to_config.py --screen ID,ID,...
        check built creatures against the in-game rules before their mesh
        run (uploaded or not); exit 1 if any fails
    python3 tools/art/to_config.py --promoted PATH
        first add every master-list id named in the reviewer's PROMOTED.log
        (PATH) to REVIEWED, then rewrite the block

A creature joins the game when all of these hold:
  - it is on the master list (tools/art/roster/master/master-list.json),
  - tools/art builds it (a roster JSON entry or a hand-built creature),
  - its meshes are uploaded (tools/art/blender/assets.json, Image colours),
  - it passed the strict review (REVIEWED: tools/art/roster/master/reviewed.txt,
    one id a line, synced from the reviewer's PROMOTED.log; nothing ships
    unreviewed, Alex Nov 5),
  - it is not already written by hand above the generated block,
  - it meets the in-game rules: its stand-in's voxel boxes within its tier's
    BOX_BUDGET and not under its detail floor (floor_of), and neither the
    stand-in nor the Blender mesh glowing below GLOW_FROM. A creature that
    misses any is held back, with every reason printed.
Hand-written entries always win: to tune one creature, move its line out of
the generated block and edit it there.

Each generated entry:
  rarity          the master list's tier
  coinsPerSecond  a whole number inside its tier's band (BANDS), picked by a
                  stable hash of the id, so it never changes between runs
  mountSpeed      its tier's speed (MOUNT)
  pools           from the master list's family (POOLS). If none of those
                  eggs rolls the tier, the first pool in FALLBACK that does
                  is used instead, so no creature is left unhatchable.
Eggs roll a tier first, then a species in it (config/eggs.luau), so a new
creature only splits its own tier's share: no other tier's odds move.
"""
import hashlib
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path[:0] = [HERE, os.path.join(HERE, 'blender')]
CONFIG = os.path.join(ROOT, 'games', 'hatchery-heist', 'config', 'creatures.luau')
EGGS = os.path.join(ROOT, 'games', 'hatchery-heist', 'config', 'eggs.luau')
MASTER = os.path.join(HERE, 'roster', 'master', 'master-list.json')
ASSETS = os.path.join(HERE, 'blender', 'assets.json')
REVIEWED = os.path.join(HERE, 'roster', 'master', 'reviewed.txt')

TIERS = ['Common', 'Uncommon', 'Rare', 'Ultra Rare', 'Epic', 'Legendary', 'Godly']
# Income bands per tier, inside the hand-tuned ones (tests/Config.spec: each
# tier earns more than the one below, best / worst <= 1000).
BANDS = {'Common': (1, 3), 'Uncommon': (4, 10), 'Rare': (15, 35), 'Ultra Rare': (60, 90),
         'Epic': (130, 200), 'Legendary': (400, 500), 'Godly': (800, 1000)}
MOUNT = {'Common': 18, 'Uncommon': 20, 'Rare': 22, 'Ultra Rare': 25, 'Epic': 28, 'Legendary': 32, 'Godly': 36}
# Family -> egg pools (agreed with the master-list thread, Nov 5). Every
# family on the master list must be here; --check fails otherwise.
POOLS = {}
for _pool, _families in {
    'Barnyard': ['Farm', 'Pet', 'City', 'Garden'],
    'Meadow': ['Woodland', 'Pond', 'Shore', 'Bug', 'Bird', 'Jungle', 'Savanna', 'Desert', 'Outback', 'Arctic',
               'Ocean', 'Invented', 'Candy'],
    'Moonlit': ['Spooky', 'Mutant', 'Fantasy', 'Mythic', 'Spirit', 'Cosmic', 'Crystal', 'Mechanical', 'Elemental',
                'Dino'],
}.items():
    for _f in _families:
        POOLS[_f] = [_pool]
FALLBACK = ['Meadow', 'Barnyard', 'Moonlit']
ELEMENTS = {'Ember', 'Glacial', 'Nature', 'Storm'}
# The in-game rules a creature's voxel boxes (VoxelArt, the stand-in drawn
# before meshes load) must meet, as games/hatchery-heist/tests/VoxelArt.spec
# checks them: a box budget per tier, and no glow below Ultra Rare. A built
# creature that misses one is left out (and printed) until its builder fixes it.
# Common is 31, not the spec's 36: its "more detailed as rarity rises" check
# wants the fewest-box Uncommon (18 boxes) at least 60% of the heaviest Common.
BOX_BUDGET = {'Common': 31, 'Uncommon': 44, 'Rare': 60, 'Ultra Rare': 80, 'Epic': 120, 'Legendary': 450,
              'Godly': 800}
GLOW_FROM = 'Ultra Rare'
# Stand-in parts drawn apart from the body on purpose (orbiting pieces, bubbles,
# dust motes, rain, a rain cloud); every other voxel must touch the body.
LOOSE_PARTS = {'orbit', 'bubble', 'motes', 'rain', 'cloud'}
DETACHED = 'detached stand-in piece'

BEGIN = '\t\t-- BEGIN generated by tools/art/to_config.py: do not edit by hand (see its docstring)\n'
END = '\t\t-- END generated\n'
WIDTH = 110  # stylua.toml column_width; a tab counts 4


def egg_tiers():
    """{pool: set of tiers its egg rolls}, read from config/eggs.luau."""
    with open(EGGS) as f:
        src = f.read()
    out = {}
    for m in re.finditer(r'pool = "(\w+)",\s*tiers = \{(.*?)\n\t\t\}', src, re.S):
        tiers = set(re.findall(r'^\s*(?:\["([^"]+)"\]|(\w+)) = \d', m.group(2), re.M))
        out.setdefault(m.group(1), set()).update(a or b for a, b in tiers)
    return out


def split(src):
    """(before, generated, after) of creatures.luau; the block is added just
    before the species table closes when it is not there yet."""
    if BEGIN in src:
        head, rest = src.split(BEGIN, 1)
        body, tail = rest.split(END, 1)
        return head, body, tail
    close = re.search(r'^\t\},\n\t-- Mutations', src, re.M)
    if not close:
        raise SystemExit(f'no end of the species table in {CONFIG}')
    return src[:close.start()], '', src[close.start():]


def hand_ids(text):
    return set(re.findall(r'^\t\t(\w+) = \{', text, re.M))


def income(cid, tier):
    lo, hi = BANDS[tier]
    h = int(hashlib.sha1(cid.encode()).hexdigest(), 16)
    return lo + h % (hi - lo + 1)


def pools_for(c, eggs):
    fam = c['family']
    if fam not in POOLS:
        raise SystemExit(f'{c["id"]}: family {fam} has no egg pool in to_config.POOLS')
    pools = [p for p in POOLS[fam] if c['tier'] in eggs.get(p, ())]
    if not pools:
        pools = [next(p for p in FALLBACK if c['tier'] in eggs.get(p, ()))]
    return pools


def line(c, eggs):
    fields = [f'rarity = "{c["tier"]}"', f'coinsPerSecond = {income(c["id"], c["tier"])}',
              f'mountSpeed = {MOUNT[c["tier"]]}',
              'pools = { ' + ', '.join(f'"{p}"' for p in pools_for(c, eggs)) + ' }']
    if c.get('element') in ELEMENTS:
        fields.append(f'element = "{c["element"]}"')
    one = '\t\t' + c['id'] + ' = { ' + ', '.join(fields) + ' },\n'
    if len(one.expandtabs(4)) - 1 <= WIDTH:
        return one
    return '\t\t' + c['id'] + ' = {\n' + ''.join(f'\t\t\t{f},\n' for f in fields) + '\t\t},\n'


def reviewed():
    if not os.path.exists(REVIEWED):
        return set()
    with open(REVIEWED) as f:
        return {ln.split('#')[0].strip() for ln in f if ln.split('#')[0].strip()}


def sync_promoted(path):
    """Adds to REVIEWED every master-list id the reviewer's log promotes.
    Ids are only ever added: a later fail is fixed by its builder, and a
    creature leaves the game only by a hand edit here."""
    with open(MASTER) as f:
        known = {c['id'] for c in json.load(f)['creatures']}
    have = reviewed()
    new = []
    with open(path) as f:
        for ln in f:
            if 'promoted' not in ln:
                continue
            for cid in re.findall(r'\b([A-Z][A-Za-z0-9]+)\b', ln.split('promoted', 1)[1]):
                if cid in known and cid not in have:
                    have.add(cid)
                    new.append(cid)
    head = '# Creatures that passed the strict review (synced from PROMOTED.log by to_config.py --promoted).\n'
    with open(REVIEWED, 'w') as f:
        f.write(head + ''.join(f'{cid}\n' for cid in sorted(have)))
    print(f'reviewed.txt: {len(new)} added, {len(have)} in all')


def floor_of(rarity):
    """The fewest boxes a stand-in of this tier may have: VoxelArt.spec wants
    each tier's plainest at least 60% of the tier below's busiest, and the
    tier below may fill its budget. Common has no floor."""
    i = TIERS.index(rarity)
    return BOX_BUDGET[TIERS[i - 1]] * 6 // 10 if i else 0


def detached(c):
    """Pieces of the stand-in that touch nothing else, not even at an edge or
    corner (26-neighbour contact), as (parts, first voxel), biggest first.
    The largest piece is the creature; a piece made only of LOOSE_PARTS is
    meant to float."""
    owner = {}
    for p in c.parts:
        for v in p.v:
            owner[v] = p.name
    steps = [(a, b, d) for a in (-1, 0, 1) for b in (-1, 0, 1) for d in (-1, 0, 1) if (a, b, d) != (0, 0, 0)]
    seen, pieces = set(), []
    for start in owner:
        if start in seen:
            continue
        seen.add(start)
        todo, piece = [start], []
        while todo:
            x, y, z = todo.pop()
            piece.append((x, y, z))
            for a, b, d in steps:
                n = (x + a, y + b, z + d)
                if n in owner and n not in seen:
                    seen.add(n)
                    todo.append(n)
        pieces.append(piece)
    pieces.sort(key=len, reverse=True)
    out = []
    for piece in pieces[1:]:
        parts = sorted({owner[v] for v in piece})
        if not set(parts) <= LOOSE_PARTS:
            out.append((parts, min(piece)))
    return out


def art_problems(c, fine=None):
    """Every rule a built creature breaks, as a list of reasons (empty when it
    passes): every part rides the body (export.py's check), the box budget and
    detail floor, no detached stand-in piece (see `detached`), and glow. `c`
    is its in-game build (the voxel boxes of the stand-in drawn before meshes
    load). `fine` is its Blender build, the reviewed mesh: the
    game draws that mesh's glowing voxels as neon pieces at any tier
    (CreatureMeshes glow), so it may only glow from GLOW_FROM up as well."""
    from voxkit import greedy_boxes, merged_boxes
    from describe import check_parents
    from export import parent_of
    out = []
    try:  # export.py stops on a part with no way back to the body
        check_parents(c.species, {p.name: parent_of(p, c.parts) for p in c.parts})
    except ValueError as e:
        out.append(f'stand-in parts: {str(e).split(": ", 1)[1]}')
    n, glow = 0, False
    for p in c.parts:
        a, b = greedy_boxes(p.v), merged_boxes(p.v)
        boxes = b if len(b) <= len(a) else a
        n += len(boxes)
        glow = glow or any(key[1] for *_, key in boxes)
    if n > BOX_BUDGET[c.rarity]:
        out.append(f'{n} voxel boxes, {c.rarity} budget is {BOX_BUDGET[c.rarity]}')
    if n < floor_of(c.rarity):
        out.append(f'{n} voxel boxes, {c.rarity} detail floor is {floor_of(c.rarity)}')
    below = TIERS.index(c.rarity) < TIERS.index(GLOW_FROM)
    if glow and below:
        out.append(f'glows, but only {GLOW_FROM} and up may')
    loose = detached(c)
    if loose:
        where = ', '.join(f'{"+".join(parts)} at {v}' for parts, v in loose[:3])
        out.append(f'{DETACHED}{"s" if len(loose) > 1 else ""} ({len(loose)}): {where}')
    if fine is not None and below:
        lit = sum(1 for p in fine.parts for _, g in p.v.values() if g)
        if lit:
            out.append(f'its mesh glows ({lit} voxels), but only {GLOW_FROM} and up may')
    return out


def hold_reasons(cid, why, live):
    """The reasons that hold `cid` back. The detached-piece rule came after
    some creatures went live: a live one is reported, never dropped, until its
    roster fix lands."""
    loose = [w for w in why if w.startswith(DETACHED)]
    if cid in live and loose:
        print(f'live, kept: {cid}: {"; ".join(loose)}', file=sys.stderr)
        return [w for w in why if not w.startswith(DETACHED)]
    return why


def problems_of(ids):
    """{id: [reasons]} for these built creatures, both builds checked."""
    from creatures import build_all
    from describe import DETAIL
    ids = set(ids)
    art = {a.species: a for a in build_all(only=ids)}
    below = {i for i, a in art.items() if TIERS.index(a.rarity) < TIERS.index(GLOW_FROM)}
    fine = {a.species: a for a in build_all(DETAIL, only=below)} if below else {}
    return {i: art_problems(art[i], fine.get(i)) for i in ids if i in art}


def generate(src):
    from creatures import ROSTER
    head, gen, tail = split(src)
    hand = hand_ids(head) | hand_ids(tail)
    live = hand_ids(gen)
    with open(MASTER) as f:
        master = json.load(f)['creatures']
    with open(ASSETS) as f:
        uploaded = {k for k, v in json.load(f)['models'].items() if v.get('textureType') == 'Image'}
    built = {sid: rarity for sid, rarity, _ in ROSTER}
    for c in master:
        if c['family'] not in POOLS:
            raise SystemExit(f'family {c["family"]} ({c["id"]}) has no egg pool in to_config.POOLS')
    eggs = egg_tiers()
    passed = reviewed()
    rows = [c for c in master if c['id'] in built and c['id'] in uploaded and c['id'] not in hand
            and c['id'] in passed]
    if rows:
        held = problems_of(c['id'] for c in rows)
        for cid, why in sorted(held.items()):
            why[:] = hold_reasons(cid, why, live)
            if why:
                print(f'held back: {cid}: {"; ".join(why)}', file=sys.stderr)
        rows = [c for c in rows if not held[c['id']]]
    for c in rows:
        if built[c['id']] != c['tier']:
            raise SystemExit(f'{c["id"]}: built as {built[c["id"]]} but the master list says {c["tier"]}')
    rows.sort(key=lambda c: (TIERS.index(c['tier']), c['id']))
    body, tier = '', None
    for c in rows:
        if c['tier'] != tier:
            tier = c['tier']
            n = sum(1 for r in rows if r['tier'] == tier)
            body += f'\t\t-- {tier}: {n} from the roster\n'
        body += line(c, eggs)
    return head + BEGIN + body + END + tail, rows


def screen(ids):
    """Checks built creatures against the in-game rules whether or not they
    are uploaded or reviewed, so a batch is screened before its mesh run."""
    from creatures import ROSTER
    built = {sid for sid, _, _ in ROSTER}
    missing = [i for i in ids if i not in built]
    found = problems_of(i for i in ids if i in built)
    bad = 0
    for i in ids:
        why = ['not built (no roster entry)'] if i in missing else found[i]
        bad += bool(why)
        print(f'{i}: {"; ".join(why) if why else "ok"}')
    print(f'{len(ids) - bad} of {len(ids)} pass')
    return bad


def main():
    if '--screen' in sys.argv:
        ids = [i for i in re.split(r'[\s,]+', sys.argv[sys.argv.index('--screen') + 1]) if i]
        sys.exit(1 if screen(ids) else 0)
    if '--promoted' in sys.argv:
        sync_promoted(sys.argv[sys.argv.index('--promoted') + 1])
    with open(CONFIG) as f:
        src = f.read()
    out, rows = generate(src)
    if '--check' in sys.argv:
        if out != src:
            print('config/creatures.luau generated block is out of date: run python3 tools/art/to_config.py')
            sys.exit(1)
        print(f'config/creatures.luau generated block is current ({len(rows)} creatures)')
        return
    with open(CONFIG, 'w') as f:
        f.write(out)
    print(f'wrote {len(rows)} generated creatures into {os.path.relpath(CONFIG, ROOT)}')


if __name__ == '__main__':
    main()
