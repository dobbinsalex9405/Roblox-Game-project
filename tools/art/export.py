"""Writes games/hatchery-heist/src/shared/VoxelArt.luau from creatures.py.

Run from anywhere:  python3 tools/art/export.py
The game draws each creature from this data (src/client/CreatureView.luau).
CI checks the file is up to date (tests/VoxelArt.spec.luau checks every
species has art; tools/art/check.sh re-runs this and diffs).

Axes: the art is built with x right, y back (front is -y) and z up. Roblox
has Y up and its front is -Z, so art (x, y, z) becomes Roblox (x, z, y),
centred on x and z with the feet at Y = 0. Numbers are in voxels."""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

from creatures import VOXEL, build_all, in_game  # noqa: E402
from voxkit import greedy_boxes, merged_boxes  # noqa: E402

sys.path.insert(0, os.path.join(HERE, 'blender'))
from describe import check_parents  # noqa: E402

OUT = os.path.join(HERE, '..', '..', 'games', 'hatchery-heist', 'src', 'shared', 'VoxelArt.luau')

# Parts that ride on another part: they keep still against it, so when the
# head nods its eyes, ears, horns and crest nod with it.
def parent_of(part, parts):
    if part.name == 'body':
        return None
    if part.name in ('eyes', 'ears'):
        return 'head'
    if part.name in ('head', 'wingL', 'wingR', 'tail') or part.name.startswith('leg'):
        return 'body'  # a moving part rides the body, never another mover (no parent loops)
    # Whichever moving part it sits closest to (body, head, a wing or the
    # tail): the most voxels touching it, even corner to corner; a part that
    # floats free (a crown, a halo of horns) goes with the nearest one.
    best, best_key = 'body', None
    for other in parts:
        if other is part or other.name not in ('body', 'head', 'wingL', 'wingR', 'tail'):
            continue
        touching = 0
        for (x, y, z) in part.v:
            if any((x + dx, y + dy, z + dz) in other.v
                   for dx in (-1, 0, 1) for dy in (-1, 0, 1) for dz in (-1, 0, 1)):
                touching += 1
        nearest = min(sum((a - b) ** 2 for a, b in zip(v, w)) for v in part.v for w in other.v)
        key = (touching, -nearest, other.name == 'head')
        if best_key is None or key > best_key:
            best, best_key = other.name, key
    return best


def num(v):
    v = round(v * 2) / 2  # whole or half voxels
    return str(int(v)) if v == int(v) else repr(v)


def export():
    creatures, waiting = in_game(build_all())
    if waiting:
        print('art not in config/creatures.luau yet (left out): ' + ', '.join(waiting))
    lines = [
        '--!strict',
        '-- GENERATED by tools/art/export.py from tools/art/creatures.py. Do not edit:',
        '-- change the art there and run `python3 tools/art/export.py`.',
        '--',
        '-- Every creature as voxel boxes, in voxels (one voxel = `voxel` studs).',
        '-- Y is up, the front is -Z, the feet are at Y = 0 and X, Z are centred.',
        '-- Each part lists its boxes as a flat array, seven numbers a box:',
        '-- min x, min y, min z, size x, size y, size z, palette index. A palette',
        '-- entry ending in "*" glows (Neon).',
        '',
        'export type Part = {',
        '\tname: string,',
        '\tanim: string,',
        '\tparent: string?,',
        '\tpivot: { number },',
        '\tboxes: { number },',
        '}',
        'export type Art = {',
        '\trarity: string,',
        '\tsize: { number },',
        '\tpalette: { string },',
        '\tparts: { Part },',
        '}',
        '',
        'local VoxelArt: { voxel: number, species: { [string]: Art } } = {',
        f'\tvoxel = {VOXEL},',
        '\tspecies = {',
    ]
    total = 0
    for c in creatures:
        lo, hi = c.bounds()
        ox, oy, oz = -(lo[0] + hi[0]) / 2, -(lo[1] + hi[1]) / 2, -lo[2]
        palette, index = [], {}
        part_lines = []
        check_parents(c.species, {p.name: parent_of(p, c.parts) for p in c.parts})
        for p in c.parts:
            a, b = greedy_boxes(p.v), merged_boxes(p.v)
            boxes = b if len(b) <= len(a) else a
            total += len(boxes)
            flat = []
            for (x, y, z, sx, sy, sz, key) in boxes:
                if key not in index:
                    rgb, glow = key
                    palette.append('%02X%02X%02X%s' % (rgb[0], rgb[1], rgb[2], '*' if glow else ''))
                    index[key] = len(palette)
                # art (x, y, z) -> Roblox (x, z, y)
                flat += [num(x + ox), num(z + oz), num(y + oy), str(sx), str(sz), str(sy), str(index[key])]
            px, py, pz = p.pivot
            parent = parent_of(p, c.parts)
            part_lines.append('\t\t\t\t{')
            part_lines.append(f'\t\t\t\t\tname = "{p.name}",')
            part_lines.append(f'\t\t\t\t\tanim = "{p.anim}",')
            if parent:
                part_lines.append(f'\t\t\t\t\tparent = "{parent}",')
            part_lines.append(f'\t\t\t\t\tpivot = {{ {num(px + ox)}, {num(pz + oz)}, {num(py + oy)} }},')
            part_lines.append('\t\t\t\t\tboxes = {')
            for i in range(0, len(flat), 7 * 8):
                part_lines.append('\t\t\t\t\t\t' + ', '.join(flat[i:i + 7 * 8]) + ',')
            part_lines.append('\t\t\t\t\t},')
            part_lines.append('\t\t\t\t},')
        size = [hi[0] - lo[0], hi[2] - lo[2], hi[1] - lo[1]]
        lines.append(f'\t\t{c.species} = {{')
        lines.append(f'\t\t\trarity = "{c.rarity}",')
        lines.append(f'\t\t\tsize = {{ {size[0]}, {size[1]}, {size[2]} }},')
        lines.append('\t\t\tpalette = { ' + ', '.join(f'"{s}"' for s in palette) + ' },')
        lines.append('\t\t\tparts = {')
        lines += part_lines
        lines.append('\t\t\t},')
        lines.append('\t\t},')
    lines += ['\t},', '}', '', 'return VoxelArt', '']
    with open(OUT, 'w') as f:
        f.write('\n'.join(lines))
    return total


if __name__ == '__main__':
    n = export()
    print(f'wrote {os.path.normpath(OUT)}: {n} boxes')
